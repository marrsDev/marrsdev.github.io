#!/usr/bin/env node
/**
 * build-seo.js — generates the SEO <head> block, the visually-hidden <h1>,
 * the JSON-LD graph, sitemap.xml and robots.txt for every page listed in
 * pages.json.
 *
 * Run from the repo root:   node seo-tools/build-seo.js
 *
 * Idempotent: everything it writes sits between SEO:* markers, and it strips
 * any hand-written <title>, canonical, description, og:/twitter: tags first,
 * so running it twice does not duplicate anything.
 */
'use strict';

const fs = require('fs');
const path = require('path');

// Where the published site lives. Supports two layouts without editing the code:
//   <repo>/cb-app.public   (this workspace)
//   <repo>/docs            (the production repo publishes from docs/)
// Override explicitly with SEO_ROOT, resolved relative to the repo root (or
// absolute if you pass an absolute path).
const REPO_ROOT = path.resolve(__dirname, '..');
function resolveSiteRoot() {
  if (process.env.SEO_ROOT) {
    const p = path.resolve(REPO_ROOT, process.env.SEO_ROOT);
    if (!fs.existsSync(p)) {
      console.error(`SEO_ROOT is set to "${process.env.SEO_ROOT}" but ${p} does not exist`);
      process.exit(1);
    }
    return p;
  }
  for (const c of ['cb-app.public', 'docs']) {
    const p = path.resolve(REPO_ROOT, c);
    if (fs.existsSync(p)) return p;
  }
  console.error(`Could not find the published site folder. Expected one of: ${path.join(REPO_ROOT, 'cb-app.public')} or ${path.join(REPO_ROOT, 'docs')}`);
  process.exit(1);
}
const ROOT = resolveSiteRoot();
const DATA = JSON.parse(fs.readFileSync(path.join(__dirname, 'pages.json'), 'utf8'));
const SITE = DATA.site;

const HEAD_START = '<!-- SEO:HEAD:START (generated by seo-tools/build-seo.js - do not edit by hand) -->';
const HEAD_END = '<!-- SEO:HEAD:END -->';
const H1_START = '<!-- SEO:H1:START -->';
const H1_END = '<!-- SEO:H1:END -->';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/* ---------------- HTML helpers ---------------- */

function decodeEntities(s) {
  const map = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ', rsquo: '\u2019', lsquo: '\u2018', ldquo: '\u201c', rdquo: '\u201d', hellip: '\u2026', mdash: '\u2014', ndash: '\u2013' };
  return String(s)
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(parseInt(n, 10)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCharCode(parseInt(n, 16)))
    .replace(/&([a-z]+);/gi, (m, name) => (map[name] !== undefined ? map[name] : m));
}

function toText(html) {
  return decodeEntities(String(html).replace(/<[^>]*>/g, ' '))
    .replace(/\s+/g, ' ')
    .trim();
}

/** Returns { inner, end } for the balanced <tag>...</tag> starting at startIdx. */
function sliceBalanced(html, startIdx, tag) {
  const open = new RegExp('<' + tag + '\\b', 'gi');
  const close = new RegExp('</' + tag + '>', 'gi');
  open.lastIndex = startIdx;
  const first = open.exec(html);
  if (!first || first.index !== startIdx) return null;

  const innerStart = first.index + first[0].length;
  let depth = 0;
  let idx = startIdx;
  for (;;) {
    open.lastIndex = idx;
    close.lastIndex = idx;
    const o = open.exec(html);
    const c = close.exec(html);
    if (!c) return null;
    if (o && o.index < c.index) {
      depth++;
      idx = o.index + o[0].length;
    } else {
      depth--;
      const end = c.index + c[0].length;
      if (depth === 0) return { inner: html.slice(innerStart, c.index), end };
      idx = end;
    }
  }
}

/**
 * Parses the visible FAQ list (<ul class="faqs">) into Question/Answer pairs.
 * Google requires FAQPage content to be visible on the page, so the schema is
 * derived from the markup rather than hand-maintained. Entries whose heading is
 * not a question (no "?") are skipped, since they are not valid FAQ entries.
 */
function extractFaqs(html) {
  const marker = html.match(/<ul class="faqs">/i);
  if (!marker) return [];
  const list = sliceBalanced(html, marker.index, 'ul');
  if (!list) return [];

  const faqs = [];
  let idx = 0;
  for (;;) {
    const li = list.inner.indexOf('<li>', idx);
    if (li === -1) break;
    const item = sliceBalanced(list.inner, li, 'li');
    if (!item) break;
    idx = item.end;

    const qm = item.inner.match(/<h[34]>([\s\S]*?)<\/h[34]>/i);
    const am = item.inner.match(/<p>([\s\S]*?)<\/p>/i);
    if (!qm || !am) continue;

    const question = toText(qm[1]);
    const answer = toText(am[1]);
    if (!question.includes('?') || !answer) continue;
    faqs.push({ q: question, a: answer });
  }
  return faqs;
}

/* ---------------- JSON-LD ---------------- */

function buildJsonLd(page, faqs) {
  const url = SITE.origin + page.path;
  const orgId = SITE.origin + '/#organization';
  const siteId = SITE.origin + '/#website';

  const graph = [
    {
      '@type': 'Organization',
      '@id': orgId,
      name: SITE.name,
      url: SITE.origin + '/',
      logo: { '@type': 'ImageObject', url: SITE.origin + SITE.logo },
      areaServed: { '@type': 'Country', name: SITE.areaServed },
      contactPoint: [{
        '@type': 'ContactPoint',
        telephone: SITE.telephone,
        contactType: 'sales',
        areaServed: 'KE',
        availableLanguage: ['en']
      }],
      sameAs: SITE.sameAs
    },
    {
      '@type': 'WebSite',
      '@id': siteId,
      url: SITE.origin + '/',
      name: SITE.name,
      inLanguage: SITE.language,
      publisher: { '@id': orgId }
    },
    {
      '@type': 'WebPage',
      '@id': url + '#webpage',
      url: url,
      name: page.title,
      description: page.description,
      inLanguage: SITE.language,
      isPartOf: { '@id': siteId },
      about: { '@id': orgId },
      primaryImageOfPage: { '@type': 'ImageObject', url: SITE.origin + page.ogImage }
    },
    {
      '@type': 'BreadcrumbList',
      '@id': url + '#breadcrumb',
      itemListElement: page.breadcrumb.map((b, i) => ({
        '@type': 'ListItem',
        position: i + 1,
        name: b.name,
        item: SITE.origin + b.path
      }))
    }
  ];

  if (faqs && faqs.length) {
    graph.push({
      '@type': 'FAQPage',
      '@id': url + '#faq',
      isPartOf: { '@id': url + '#webpage' },
      mainEntity: faqs.map((f) => ({
        '@type': 'Question',
        name: f.q,
        acceptedAnswer: { '@type': 'Answer', text: f.a }
      }))
    });
  }

  return { '@context': 'https://schema.org', '@graph': graph };
}

/* ---------------- head block ---------------- */

function buildHeadBlock(page, faqs) {
  const url = SITE.origin + page.path;
  const img = SITE.origin + page.ogImage;
  const jsonld = JSON.stringify(buildJsonLd(page, faqs)).replace(/</g, '\\u003c');

  return [
    HEAD_START,
    `    <title>${esc(page.title)}</title>`,
    `    <meta name="description" content="${esc(page.description)}">`,
    `    <link rel="canonical" href="${esc(url)}">`,
    `    <meta name="robots" content="index,follow,max-image-preview:large,max-snippet:-1">`,
    '',
    `    <meta property="og:type" content="website">`,
    `    <meta property="og:site_name" content="${esc(SITE.name)}">`,
    `    <meta property="og:locale" content="${esc(SITE.locale)}">`,
    `    <meta property="og:title" content="${esc(page.title)}">`,
    `    <meta property="og:description" content="${esc(page.description)}">`,
    `    <meta property="og:url" content="${esc(url)}">`,
    `    <meta property="og:image" content="${esc(img)}">`,
    `    <meta property="og:image:type" content="image/jpeg">`,
    `    <meta property="og:image:width" content="1200">`,
    `    <meta property="og:image:height" content="630">`,
    `    <meta property="og:image:alt" content="${esc(page.ogImageAlt)}">`,
    '',
    `    <meta name="twitter:card" content="summary_large_image">`,
    `    <meta name="twitter:title" content="${esc(page.title)}">`,
    `    <meta name="twitter:description" content="${esc(page.description)}">`,
    `    <meta name="twitter:image" content="${esc(img)}">`,
    `    <meta name="twitter:image:alt" content="${esc(page.ogImageAlt)}">`,
    '',
    `    <script type="application/ld+json">${jsonld}</script>`,
    `    ${HEAD_END}`
  ].join('\n');
}

function buildH1Block(page) {
  return [
    H1_START,
    `    <h1 class="sr-only">${esc(page.h1)}</h1>`,
    `    ${H1_END}`
  ].join('\n');
}

/* ---------------- transform one page ---------------- */

function transform(html, page) {
  const faqs = extractFaqs(html);

  // 1. remove previously generated blocks. The leading \n is the exact newline
  //    the insertion step below adds, so re-running the build leaves the file
  //    byte-identical instead of nibbling the indentation of the next line.
  html = html.replace(/\n<!-- SEO:HEAD:START[\s\S]*?<!-- SEO:HEAD:END -->/g, '');
  html = html.replace(/\n<!-- SEO:H1:START[\s\S]*?<!-- SEO:H1:END -->/g, '');

  // 2. remove hand-written equivalents so nothing is duplicated
  html = html.replace(/<title>[\s\S]*?<\/title>\s*/gi, '');
  html = html.replace(/<link[^>]+rel=["']canonical["'][^>]*>\s*/gi, '');
  html = html.replace(/<meta[^>]+name=["']description["'][^>]*>\s*/gi, '');
  html = html.replace(/<meta[^>]+property=["']og:[^"']*["'][^>]*>\s*/gi, '');
  html = html.replace(/<meta[^>]+name=["']twitter:[^"']*["'][^>]*>\s*/gi, '');

  // 3. inject the fresh head block near the TOP of <head> (right after the
  //    viewport meta). These pages carry a large inline <style>, and some social
  //    crawlers only read the first part of a document, so metadata placed just
  //    before </head> can be missed.
  const headBlock = buildHeadBlock(page, faqs);
  const anchor = html.match(/<meta[^>]+name=["']viewport["'][^>]*>/i)
    || html.match(/<meta[^>]+charset=["'][^"']*["'][^>]*>/i)
    || html.match(/<head[^>]*>/i);
  if (!anchor) throw new Error(page.file + ': no <head> anchor found');
  html = html.slice(0, anchor.index + anchor[0].length) +
    '\n' + headBlock +
    html.slice(anchor.index + anchor[0].length);

  // 4. inject the visually-hidden h1 immediately after <body>
  const bodyMatch = html.match(/<body[^>]*>/i);
  if (!bodyMatch) throw new Error(page.file + ': no <body> found');
  const h1Block = buildH1Block(page);
  html = html.slice(0, bodyMatch.index + bodyMatch[0].length) +
    '\n' + h1Block +
    html.slice(bodyMatch.index + bodyMatch[0].length);

  return { html, faqs };
}

/* ---------------- main ---------------- */

function main() {
  let changed = 0;
  const summary = [];

  for (const page of DATA.pages) {
    const file = path.join(ROOT, page.file);
    if (!fs.existsSync(file)) {
      console.error(`  ! ${page.file} listed in pages.json but not found - skipped`);
      continue;
    }
    const before = fs.readFileSync(file, 'utf8');
    const { html, faqs } = transform(before, page);
    if (html !== before) {
      fs.writeFileSync(file, html);
      changed++;
    }
    summary.push(`${page.file}: faq=${faqs.length}`);
  }

  // sitemap.xml — pages with "inSitemap": false are deliberately left out
  // (still generating their head tags, but not advertised until they are ready).
  const sitemapPages = DATA.pages.filter((p) => p.inSitemap !== false);
  const excluded = DATA.pages.filter((p) => p.inSitemap === false);

  const urls = sitemapPages.map((p) => [
    '  <url>',
    `    <loc>${esc(SITE.origin + p.path)}</loc>`,
    `    <lastmod>${SITE.lastmod}</lastmod>`,
    `    <changefreq>${p.sitemap.changefreq}</changefreq>`,
    `    <priority>${p.sitemap.priority}</priority>`,
    '  </url>'
  ].join('\n')).join('\n');

  fs.writeFileSync(path.join(ROOT, 'sitemap.xml'),
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    urls + '\n</urlset>\n');

  // robots.txt — the disallow list lives in pages.json so it survives rebuilds.
  // Hand-editing robots.txt previously got silently reverted by this script.
  const disallow = Array.isArray(SITE.disallow) ? SITE.disallow : [];
  fs.writeFileSync(path.join(ROOT, 'robots.txt'),
    'User-agent: *\n' +
    'Allow: /\n' +
    disallow.map((d) => `Disallow: ${d}\n`).join('') +
    '\n' +
    `Sitemap: ${SITE.origin}/sitemap.xml\n`);

  console.log(`build-seo: site root = ${ROOT}`);
  console.log(`build-seo: processed ${DATA.pages.length} page(s), ${changed} modified`);
  summary.forEach((s) => console.log('  ' + s));
  if (excluded.length) {
    console.log(`  excluded from sitemap (inSitemap:false): ${excluded.map((p) => p.file).join(', ')}`);
  }
  console.log('  wrote sitemap.xml and robots.txt');
}

main();
